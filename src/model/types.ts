/* Document model, format version 2. Everything is in grid cells; off-grid geometry (structures, edge structures,
   stamps, notes, keys) may be fractional, kept on the 1/96-cell lattice (see geom/lattice.ts). Rooms and doors
   stay on whole cells / cell edges. */

export interface Rect {
  x: number;
  y: number;
  w: number;
  h: number;
}
export interface Seg {
  x1: number;
  y1: number;
  x2: number;
  y2: number;
}
/** A stamp point: top-left of its 1×1 box. `id` is its stable identity, given when it is placed and kept while it is
    dragged (or carried by a room); the UE importer pairs a point with what it generated by this id. A point dropped on
    another stamp's point replaces it: the old point and its id are gone, the new one has a new id. `notes` belong to
    this copy alone (absent when empty); they move, copy and paste with it. */
export interface Pt {
  id: string;
  x: number;
  y: number;
  notes?: string;
}

export interface Area {
  id: string;
  name: string;
  color: string;
  /** ENSRegionList enum name from mvmap-types.js */
  region?: string | null;
  letter?: string | null;
}

export type LabelPos = "tl" | "tr" | "bl" | "br";

export interface Room {
  id: string;
  name: string;
  areaId: string;
  /** null = inherit the area colour */
  color: string | null;
  notes: string;
  /** "x,y" whole cells */
  cells: string[];
  /** positive integer, unique within the area */
  number?: number | null;
  labelPos?: LabelPos;
  hideName?: boolean;
}

/** A "v" edge at (x,y) divides cells (x-1,y) | (x,y); an "h" edge at (x,y) divides (x,y-1) / (x,y). */
export interface Door {
  id: string;
  x: number;
  y: number;
  o: "v" | "h";
  kind: "passage" | "door" | "oneway" | "locked";
  dir: 1 | -1;
  lockId: string | null;
}

export interface Lock {
  id: string;
  name: string;
  color: string;
  keyIds: string[];
  hideName?: boolean;
}

/** x, y: top-left of the 1×1 marker box (centre at +0.5). */
export interface Key {
  id: string;
  name: string;
  color: string;
  x: number;
  y: number;
  hideName?: boolean;
}

interface Element {
  id: string;
  name: string;
  color: string;
  notes: string;
  /** element type: a structure / edge type from mvmap-types.js, a stamp type from the document's stampCategories;
      null = unclassified */
  typeId?: string | null;
  hideName?: boolean;
}
/** A polygon vertex in cell units. */
export interface XY {
  x: number;
  y: number;
}
/** Axis-aligned rectangles, canonical (non-overlapping, see geom/region.ts); the layer is exclusive. `cuts` are
    negative space: simple polygons taken out of the rects, so the solid area is rects minus cuts. Only cuts with a
    slanted edge are kept (a cut along the grid is taken out of the rects themselves); each still bites into the
    rects, but may reach past them and may overlap other cuts. Vertices run clockwise on screen (positive signed area
    with y down). Absent when there are none. */
export interface Structure extends Element {
  rects: Rect[];
  cuts?: XY[][];
}
/** Line segments, any angle; collinear overlaps are merged within a set and exclusive across sets. */
export interface EdgeStruct extends Element {
  segs: Seg[];
}
/** How a stamp's object is placed in UE: on the ground below the marker box, or at the bottom of the box. */
export type StampAnchor = "SnapToGround" | "FloatInAir";

/** Emoji markers; each point is the top-left of a 1×1 box. Notes are written per copy (Pt.notes); the stamp's own
    `notes` stay "" (a file from before per-copy notes has them handed to every copy on load). */
export interface Stamp extends Element {
  emoji: string;
  points: Pt[];
  /** filled on load from the type's default (mvmap-ue.js stampAnchorOf); a type with anchorLocked overrides it */
  anchor?: StampAnchor;
  /** id of one of its type's tiers (StampType.tiers); see mvmap-ue.js tierOf */
  tier?: string | null;
}

/** Stamp categories, stored in the document and edited by designers; shape documented in mvmap-types.js
    defaultStampCategories. Shaped like the UE importer's settings: types[id].tiers[tier] <-> StampTypes[id].Tiers[tier];
    submenus only arrange the Type dropdown. */
export interface StampTier {
  /** stored in a stamp's `tier`; a key of the type's Tiers on the UE side */
  id: string;
  label: string;
}
export interface StampSubmenu {
  id: string;
  label: string;
}
/** What the UE importer does with a type: generates it (auto), or leaves a placeholder to be placed by hand (manual). */
export type ImportMethod = "auto" | "manual";
export interface StampType {
  /** exported as typeId; a key of StampTypes on the UE side */
  id: string;
  label: string;
  /** id of the StampSubmenu it is shown in (display only) */
  submenu?: string;
  color: string;
  emoji: string;
  anchor?: StampAnchor;
  anchorLocked?: boolean;
  /** the tiers' common name, the title of the tier dropdown (大小, 强弱); set exactly when `tiers` is */
  tierLabel?: string;
  tiers?: StampTier[];
  /** only in mvmap-types.js defaultStampCategories and in exported files: how UE imports the type (mvmap-ue.js
      importMethodOf); never stored in a document */
  importMethod?: ImportMethod;
}
export interface StampCategories {
  submenus: StampSubmenu[];
  types: StampType[];
}

export interface Note {
  id: string;
  name: string;
  text: string;
  color: string;
  /** top-left of the 1×1 note box */
  x: number;
  y: number;
  expanded: boolean;
  /** open box offset from its default spot, screen px */
  box?: { dx: number; dy: number };
  hideName?: boolean;
}

/** Freehand stroke in world px (one cell = 32 px), flat [x0,y0,x1,y1,…]. */
export interface PencilStroke {
  id: string;
  color: string;
  size: number;
  pts: number[];
}

export interface MapDoc {
  id: string;
  version: number;
  name: string;
  updated: number;
  areas: Area[];
  rooms: Room[];
  doors: Door[];
  locks: Lock[];
  keys: Key[];
  structures: Structure[];
  edgeStructs: EdgeStruct[];
  stamps: Stamp[];
  notes: Note[];
  pencil: PencilStroke[];
  /** filled on load (the defaults of mvmap-types.js when the file has none), so absent only before migrateDoc */
  stampCategories?: StampCategories;
}

export type ElementLayer = "structure" | "edge" | "stamp";
